// 2. CREATE FOOD CARDS
// ==================================



const foodGrid = document.getElementById("foodGrid");

function displayRecipes(dishes) {

    foodGrid.innerHTML = "";

    document.getElementById("noResults").style.display =
        dishes.length === 0 ? "block" : "none";

    dishes.forEach((recipe) => {

        const card = document.createElement("article");

        card.className = "food-card";

        const image = document.createElement("img");
        image.src = recipe.image;
        image.alt = recipe.name;
        image.loading = "lazy";

        const content = document.createElement("div");
        content.className = "card-content";

        const region = document.createElement("p");
        region.textContent = recipe.region;

        const title = document.createElement("h3");
        title.textContent = recipe.name;

        const hint = document.createElement("p");
        hint.textContent = "Click to view recipe →";

        content.append(region, title, hint);
        card.append(image, content);

        card.addEventListener("click", function () {
            openRecipe(recipe);
        });

        foodGrid.appendChild(card);

    });

    }


// ======================================
// 3. OPEN RECIPE POPUP
// ======================================

const modal = document.getElementById("recipeModal");

function openRecipe(recipe) {

    document.getElementById("recipeImage").src = recipe.image;

    document.getElementById("recipeTitle").textContent = recipe.name;

    document.getElementById("recipeRegion").textContent = recipe.region;

    document.getElementById("recipeDescription").textContent =
        recipe.description;

    document.getElementById("recipeTime").textContent =
        "Preparation time: " + recipe.time;

    const ingredientsList =
        document.getElementById("recipeIngredients");

    const instructionsList =
        document.getElementById("recipeInstructions");

    ingredientsList.innerHTML = "";
    instructionsList.innerHTML = "";

    recipe.ingredients.forEach(function (ingredient) {

        const item = document.createElement("li");

        item.textContent = ingredient;

        ingredientsList.appendChild(item);

    });

    recipe.instructions.forEach(function (step) {

        const item = document.createElement("li");

        item.textContent = step;

        instructionsList.appendChild(item);

    });

    modal.classList.add("active");

    document.body.style.overflow = "hidden";

}


// ======================================
// 4. CLOSE RECIPE POPUP
// ======================================

function closeRecipe() {

    modal.classList.remove("active");

    document.body.style.overflow = "";

}

document.getElementById("closeModal").addEventListener("click", closeRecipe);

modal.addEventListener("click", function (event) {

    if (event.target === modal) {
        closeRecipe();
    }

});

document.addEventListener("keydown", function (event) {

    if (event.key === "Escape") {
        closeRecipe();
    }

});


